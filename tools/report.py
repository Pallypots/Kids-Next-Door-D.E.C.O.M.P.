#!/usr/bin/env python3
"""Generate docs/PROGRESS.md from measured data only:
  analysis-local/inv/{functions,coverage}.json  (tools/funcs.py)   — inventory denominators
  build/verify-report.json                      (tools/verify.py)  — verification results
Missing inputs are reported as "unknown", never estimated.

  python -I tools/report.py
"""
import datetime
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(rel):
    p = os.path.join(ROOT, rel)
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def main():
    cov = load("analysis-local/inv/coverage.json")
    funcs = load("analysis-local/inv/functions.json")
    rep = load("build/verify-report.json")
    out = ["# Progress (generated by tools/report.py — do not edit by hand)", "",
           "Generated: %s" % datetime.date.today().isoformat(), ""]
    if rep:
        out += ["Reference build `%s`, XBE SHA-256 `%s`." % (rep["reference_build"], rep["xbe_sha256"]),
                "Checker `tools/xcheck.py` SHA-256 `%s`; compiler: %s (`%s`)." % (
                    rep["checker_sha256"], rep["compiler_version"], rep["compiler"]), ""]
    out += ["## Inventory denominators (tools/funcs.py, candidate functions — not verified boundaries)", ""]
    if cov:
        out += ["| Section | Raw bytes | Code bytes reached | Candidate functions | high / medium / low |",
                "| --- | ---: | ---: | ---: | --- |"]
        for n, c in cov.items():
            out.append("| %s | %d | %d | %d | %d / %d / %d |" % (n, c["raw_size"], c["unique_code_bytes_reached"],
                                                            c["functions"], c["high"], c["medium"], c["low"]))
        out += ["", "Ownership (game vs. CRT/XDK/middleware) inside `.text` is NOT yet classified; the named library",
                "sections (D3D, DSOUND, XACTENG, WMADEC, XPP, PSFD*, DOLBY, D3DX, XGRPH) are SDK/middleware by section",
                "name. See docs/STATE.md for the evidence-based partial map.", ""]
    else:
        out += ["unknown (run tools/funcs.py)", ""]
    out += ["## Verification results (tools/verify.py)", ""]
    if rep:
        out += ["| VA | Size | Symbol | Subsystem | Result |", "| --- | ---: | --- | --- | --- |"]
        for r in rep["results"]:
            out.append("| %s | %d | `%s` | %s | %s |" % (r["va"], r["size"], r["symbol"], r["subsystem"], r["result"]))
        m = [r for r in rep["results"] if r["result"] == "MATCH"]
        out += ["", "Relocation-aware matches with the host compiler: %d functions, %d unique bytes." % (
            len(m), sum(r["size"] for r in m))]
        if cov:
            out.append("Share of `.text` raw bytes: %.4f%% (denominator includes unclassified library code)." % (
                100.0 * sum(r["size"] for r in m) / cov[".text"]["raw_size"]))
        out += ["Matches with the ORIGINAL toolchain: 0 (toolchain unavailable — docs/toolchain.md).",
                "Exact linked match (whole XBE): not attempted.", ""]
    else:
        out += ["unknown (run tools/verify.py)", ""]
    with open(os.path.join(ROOT, "docs", "PROGRESS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote docs/PROGRESS.md")


if __name__ == "__main__":
    main()
