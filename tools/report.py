#!/usr/bin/env python3
"""Generate docs/PROGRESS.md from measured data only:
  analysis-local/inv/{functions,coverage}.json  (tools/funcs.py)   — inventory denominators
  build/verify-report.json                      (tools/verify.py)  — verification results
  build/oracle-report.json                      (tools/oracle_run.py) — differential oracle results
Missing inputs are reported as "unknown", never estimated.

  python -I tools/report.py
"""
import datetime
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(rel):
    p = os.path.join(ROOT, rel)
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def main():
    cov = load("analysis-local/inv/coverage.json")
    funcs = load("analysis-local/inv/functions.json")
    rep = load("build/verify-report.json")
    orc = load("build/oracle-report.json")
    out = ["# Progress (generated by tools/report.py — do not edit by hand)", "",
           "Generated: %s" % datetime.date.today().isoformat(), ""]
    if rep:
        out += ["Reference build `%s`, XBE SHA-256 `%s`." % (rep["reference_build"], rep["xbe_sha256"]),
                "Checker `tools/xcheck.py` SHA-256 `%s`; compiler: %s (`%s`)." % (
                    rep["checker_sha256"], rep["compiler_version"], rep["compiler"]), ""]
    out += ["## Inventory denominators (tools/funcs.py, candidate functions — not verified boundaries)", ""]
    if cov:
        out += ["| Section | Raw bytes | Code bytes reached | Candidate functions | high / medium / low |",
                "| --- | ---: | ---: | ---: | --- |"]
        for n, c in cov.items():
            out.append("| %s | %d | %d | %d | %d / %d / %d |" % (n, c["raw_size"], c["unique_code_bytes_reached"],
                                                            c["functions"], c["high"], c["medium"], c["low"]))
        totals = {}
        for c in cov.values():
            for k, n in c.get("kinds", {}).items():
                totals[k] = totals.get(k, 0) + n
        out += ["", "By kind across all sections: %s. Only `source` belongs in a function-count denominator; the rest are "
                "compiler-generated or belong to a parent function, and stay listed because a whole-image reconstruction "
                "must account for their bytes." % ", ".join("%s %d" % kv for kv in sorted(totals.items()))]
        own = load("analysis-local/inv/ownership.json")
        out += ["", "### Who owns the code (tools/ownership.py)", ""]
        if own:
            out += ["| Owner | Functions | Unique bytes | Direct evidence | Signature hint only | Inferred from neighbours | No evidence |",
                    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
            for cls, r in own["summary"].items():
                out.append("| %s | %d | %d | %d | %d | %d | %d |" % (cls, r["functions"], r["unique_bytes"], r["direct"], r["hint"], r["inferred"], r["none"]))
            game = own["summary"].get("game")
            rep_now = load("build/verify-report.json")
            if game and rep_now:
                recorded = {r["va"] for r in rep_now["results"]}
                game_vas = {k for k, v in own["functions"].items() if v[0] == "game"}
                out += ["", "**Estimate**, because most of the game row is inferred: %d of about %d game functions are recorded in config/functions.toml. "
                        "This counts source written, whatever its verification state, not a playable fraction." % (len(recorded & game_vas), game["functions"]), ""]
        else:
            out += ["unknown (run tools/ownership.py)", ""]
    else:
        out += ["unknown (run tools/funcs.py)", ""]
    out += ["## Verification results (tools/verify.py)", ""]
    if rep:
        out += ["| VA | Size | Symbol | Subsystem | Result |", "| --- | ---: | --- | --- | --- |"]
        for r in rep["results"]:
            out.append("| %s | %d | `%s` | %s | %s |" % (r["va"], r["size"], r["symbol"], r["subsystem"], r["result"]))
        m = [r for r in rep["results"] if r["result"] == "MATCH"]
        out += ["", "Relocation-aware matches with the host compiler: %d functions, %d unique bytes." % (
            len(m), sum(r["size"] for r in m))]
        if cov:
            out.append("Share of `.text` raw bytes: %.4f%% (denominator includes unclassified library code)." % (
                100.0 * sum(r["size"] for r in m) / cov[".text"]["raw_size"]))
        out += ["Matches with the ORIGINAL toolchain: 0 (toolchain unavailable — docs/toolchain.md).",
                "Exact linked match (whole XBE): not attempted.", ""]
        vt = rep.get("vtables", [])
        out += ["## Vftables (tools/verify.py)", "", "| VA | Slots | Symbol | Result |", "| --- | ---: | --- | --- |"]
        out += ["| %s | %d | `%s` | %s |" % (v["va"], v["slots"], v["symbol"], v["result"]) for v in vt]
        out += [""]
        out += ["## Differential oracle against the original code (tools/oracle_run.py)", ""]
        if orc:
            for name, r in orc["suites"].items():
                clean = sum(1 for x in r["seeds"] if x["exit"] == 0)
                det = [m for m in r["mutants"] if m["verdict"].startswith("detected")]
                out += ["Suite `%s`: runs with no observed difference %d / %d (%s). Recorded function entries reached in "
                        "every run: %d / %d. Source mutants detected%s: %d / %d. Positive control exit: %s. Harness mutation "
                        "exit: %s." % (name, clean, len(r["seeds"]), (r["seeds"][0]["summary"] or ["?"])[0],
                                       r["entries_reached"], r["entries_total"], " (by an earlier run)" if r.get("mutants_from_earlier_run") else "", len(det), len(r["mutants"]),
                                       r.get("mutant_positive_control_exit"), r["harness_mutation_exit"]), ""]
            out += ["This is behaviour evidence (Semantic-tested), not a byte match and not a proof.", ""]
        else:
            out += ["unknown (run tools/oracle_run.py)", ""]
    else:
        out += ["unknown (run tools/verify.py)", ""]
    with open(os.path.join(ROOT, "docs", "PROGRESS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote docs/PROGRESS.md")


if __name__ == "__main__":
    main()
